CREATE TABLE IF NOT EXISTS config (k TEXT PRIMARY KEY, v TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sets (id INTEGER PRIMARY KEY AUTOINCREMENT, day TEXT NOT NULL, exercise TEXT NOT NULL, weight REAL NOT NULL, reps INTEGER NOT NULL, created_at TEXT NOT NULL DEFAULT (datetime('now')));
CREATE INDEX IF NOT EXISTS idx_sets_day ON sets(day);
CREATE INDEX IF NOT EXISTS idx_sets_ex ON sets(exercise);
CREATE TABLE IF NOT EXISTS bodyweight (day TEXT PRIMARY KEY, kg REAL NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (day TEXT PRIMARY KEY, plan_id TEXT, plan_name TEXT, started_at TEXT, finished_at TEXT, note TEXT);
CREATE TABLE IF NOT EXISTS schedule (dow INTEGER PRIMARY KEY, plan_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS planned (day TEXT PRIMARY KEY, plan_id TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS user_plans (id TEXT PRIMARY KEY, name TEXT NOT NULL, when_text TEXT, items TEXT NOT NULL, updated_at TEXT NOT NULL DEFAULT (datetime('now')));
